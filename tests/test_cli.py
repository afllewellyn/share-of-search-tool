def test_the_current_month_is_never_requested():
    """Google Ads has no data for a month that hasn't finished."""
    assert last_complete_month(date(2026, 8, 1)) == date(2026, 7, 1)
    assert last_complete_month(date(2026, 8, 31)) == date(2026, 7, 1)
    assert last_complete_month(date(2026, 1, 15)) == date(2025, 12, 1)


def test_shift_months_crosses_year_boundaries():
    assert shift_months(date(2026, 1, 1), -1) == date(2025, 12, 1)
    assert shift_months(date(2026, 1, 1), -13) == date(2024, 12, 1)
    assert shift_months(date(2025, 12, 1), 1) == date(2026, 1, 1)
    assert shift_months(date(2026, 7, 1), -47) == date(2022, 8, 1)


