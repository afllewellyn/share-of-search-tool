def test_a_thinly_covered_brand_is_flagged():
    warnings = keyword_parity_warnings({
        "Acme": ["acme", "acme app", "acme login", "acme pro", "acme cloud", "acme x"],
        "Globex": ["globex"],
    })

    assert len(warnings) == 1
    assert "Globex" in warnings[0]


def test_comparable_coverage_is_not_flagged():
    assert keyword_parity_warnings({
        "Acme": ["acme", "acme app"],
        "Globex": ["globex"],
    }) == []


def test_parity_needs_two_brands_to_compare():
    assert keyword_parity_warnings({"Acme": ["a", "b", "c", "d"]}) == []


def test_duplicate_keywords_do_not_inflate_a_brands_coverage():
    assert keyword_parity_warnings({
        "Acme": ["acme"] * 9,
        "Globex": ["globex"],
    }) == []


