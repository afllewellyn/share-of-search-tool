def _range(tmp_path, config, **kwargs):
    """Resolve a request range with prompting off, as a script would."""
    options = dict(
        empty_store=True, backfill=False, months=None, date_from=None,
        date_to=None, refresh_last=None, no_prompt=True,
    )
    options.update(kwargs)
    return _resolve_range(tmp_path, config, **options)


def test_months_flag_asks_for_exactly_that_many(tmp_path, sample_config):
    start, end, reason = _range(tmp_path, sample_config, months=12)

    assert shift_months(start, 12) == shift_months(end, 1)   # 12 months inclusive
    assert "12" in reason


def test_months_flag_is_rejected_below_one(tmp_path, sample_config):
    with pytest.raises(click.ClickException, match="--months must be at least 1"):
        _range(tmp_path, sample_config, months=0)


def test_explicit_dates_beat_the_months_flag(tmp_path, sample_config):
    start, _, reason = _range(tmp_path, sample_config, months=12, date_from="2024-03")

    assert start == date(2024, 3, 1)
    assert reason == "explicit range"


def test_a_first_pull_backfills_when_nobody_can_be_asked(tmp_path, sample_config):
    """A piped or CI run must not block on a prompt nobody can see."""
    start, end, reason = _range(tmp_path, sample_config)

    assert shift_months(start, BACKFILL_MONTHS) == shift_months(end, 1)
    assert "auto-backfill" in reason


def test_the_prompt_is_suppressed_without_a_terminal(tmp_path, sample_config, monkeypatch):
    monkeypatch.setattr("sos.cli._prompt_timeframe", _unreachable)
    monkeypatch.setattr(sys.stdin, "isatty", lambda: False)

    _range(tmp_path, sample_config, no_prompt=False)   # must not raise


def _unreachable(*args, **kwargs):
    raise AssertionError("the timeframe prompt should not have been reached")


def test_no_month_before_the_last_complete_one_is_ever_requested(tmp_path, sample_config):
    _, end, _ = _range(tmp_path, sample_config, date_to="2099-01")

    assert end == last_complete_month()
